/** Sugere a moeda do turista pela região do idioma do aparelho (ex.: es-AR → ARS). */
export function detectCurrency(): CurrencyCode {
  for (const tag of navigator.languages ?? [navigator.language]) {
    try {
      const region = new Intl.Locale(tag).maximize().region;
      const match = CURRENCIES.find((c) => region && c.countries.includes(region));
      if (match) return match.code;
    } catch {
      // tag de idioma inválida: ignora
    }
  }
  return 'USD';
}

